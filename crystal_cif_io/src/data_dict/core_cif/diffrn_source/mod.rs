/// The single-value terms of the `diffrn_source` category: one variant per
/// registry single-value item, in item order.
#[derive(Debug, Clone)]
#[allow(non_camel_case_types, clippy::upper_case_acronyms)]
pub enum DiffrnSourceTerms {
    /// The `_diffrn_source_beamline` item. The variant holds the single value.
    Beamline(CharString),
    /// The `_diffrn_source_convergence_angle` item. The variant holds the single value.
    /// range constraint recorded in the dictionary _enumeration
    Convergence_angle(ConvergenceAngle),
    /// The `_diffrn_source_current` item. The variant holds the single value.
    ///
    /// The current in milliamperes at which the radiation source was
    /// operated.
    /// Units: mA (milliampere).
    /// range constraint recorded in the dictionary _enumeration
    Current(Current),
    /// The `_diffrn_source_details` item. The variant holds the single value.
    ///
    /// A description of special aspects of the source.
    Details(CharString),
    /// The `_diffrn_source_device` item. The variant holds the single value.
    /// closed code set recorded in the dictionary _enumeration_set
    Device(Device),
    /// The `_diffrn_radiation_source` item. The variant holds the single value.
    ///
    /// The source of radiation.
    Diffrn_radiation_source(CharString),
    /// The `_diffrn_source` item. The variant holds the single value.
    ///
    /// The general class of the source of radiation.
    Diffrn_source(CharString),
    /// The `_diffrn_source_ed_diffracting_area_selection` item. The variant holds the single value.
    /// closed code set recorded in the dictionary _enumeration_set
    Ed_diffracting_area_selection(EdDiffractingAreaSelection),
    /// The `_diffrn_source_facility` item. The variant holds the single value.
    Facility(CharString),
    /// The `_diffrn_source_make` item. The variant holds the single value.
    Make(CharString),
    /// The `_diffrn_source_power` item. The variant holds the single value.
    ///
    /// The power in kilowatts at which the radiation source was operated.
    /// Units: kW (kilowatt).
    /// range constraint recorded in the dictionary _enumeration
    Power(Power),
    /// The `_diffrn_source_size` item. The variant holds the single value.
    ///
    /// The dimensions of the source as viewed from the sample.
    Size(CharString),
    /// The `_diffrn_source_take-off_angle` item. The variant holds the single value.
    ///
    /// The complement of the angle in degrees between the normal to the
    /// surface of the X-ray tube target and the primary X-ray beam for
    /// beams generated by traditional X-ray tubes.
    /// Units: deg (degree of arc).
    /// range constraint recorded in the dictionary _enumeration
    TakeOffAngle(TakeOffAngle),
    /// The `_diffrn_source_target` item. The variant holds the single value.
    ///
    /// The chemical element symbol for the X-ray target (usually the anode)
    /// used to generate X-rays. This can also be used for spallation
    /// sources.
    /// closed code set recorded in the dictionary _enumeration
    Target(Target),
    /// The `_diffrn_source_type` item. The variant holds the single value.
    ///
    /// The make, model or name of the source of radiation.
    Type(CharString),
    /// The `_diffrn_source_voltage` item. The variant holds the single value.
    ///
    /// The voltage in kilovolts at which the radiation source was operated.
    /// Units: kV (kilovolt).
    /// range constraint recorded in the dictionary _enumeration
    Voltage(Voltage),
}

impl CifTerm for DiffrnSourceTerms {
    fn tag(&self) -> Tag {
        let tag = match self {
            DiffrnSourceTerms::Beamline(_) => "diffrn_source_beamline",
            DiffrnSourceTerms::Convergence_angle(_) => "diffrn_source_convergence_angle",
            DiffrnSourceTerms::Current(_) => "diffrn_source_current",
            DiffrnSourceTerms::Details(_) => "diffrn_source_details",
            DiffrnSourceTerms::Device(_) => "diffrn_source_device",
            DiffrnSourceTerms::Diffrn_radiation_source(_) => "diffrn_radiation_source",
            DiffrnSourceTerms::Diffrn_source(_) => "diffrn_source",
            DiffrnSourceTerms::Ed_diffracting_area_selection(_) => {
                "diffrn_source_ed_diffracting_area_selection"
            }
            DiffrnSourceTerms::Facility(_) => "diffrn_source_facility",
            DiffrnSourceTerms::Make(_) => "diffrn_source_make",
            DiffrnSourceTerms::Power(_) => "diffrn_source_power",
            DiffrnSourceTerms::Size(_) => "diffrn_source_size",
            DiffrnSourceTerms::TakeOffAngle(_) => "diffrn_source_take-off_angle",
            DiffrnSourceTerms::Target(_) => "diffrn_source_target",
            DiffrnSourceTerms::Type(_) => "diffrn_source_type",
            DiffrnSourceTerms::Voltage(_) => "diffrn_source_voltage",
        };
        Tag::new(tag.to_string())
    }
}

impl SingleValueTerm for DiffrnSourceTerms {
    fn value(&self) -> Value {
        match self {
            DiffrnSourceTerms::Beamline(s)
            | DiffrnSourceTerms::Details(s)
            | DiffrnSourceTerms::Diffrn_radiation_source(s)
            | DiffrnSourceTerms::Diffrn_source(s)
            | DiffrnSourceTerms::Facility(s)
            | DiffrnSourceTerms::Make(s)
            | DiffrnSourceTerms::Size(s)
            | DiffrnSourceTerms::Type(s) => Value::CharString(s.clone()),
            DiffrnSourceTerms::Convergence_angle(v) => Value::from(*v),
            DiffrnSourceTerms::Current(m) => Value::from(*m),
            DiffrnSourceTerms::Device(c) => Value::from(*c),
            DiffrnSourceTerms::Ed_diffracting_area_selection(b) => Value::from(*b),
            DiffrnSourceTerms::Power(t) => Value::from(*t),
            DiffrnSourceTerms::TakeOffAngle(u) => Value::from(*u),
            DiffrnSourceTerms::Target(w) => Value::from(*w),
            DiffrnSourceTerms::Voltage(x) => Value::from(*x),
        }
    }
}

impl Display for DiffrnSourceTerms {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.to_single_value_data())
    }
}
