//! Compute dictionary-item coverage of the real-data corpora and
//! write `tests/dict_coverage_baseline.json`.
//!
//! Usage: `cargo run --example dict_coverage_gen`
//!
//! The test `tests/dict_coverage.rs` recomputes the same number and
//! fails when coverage drops below the committed baseline. Run this
//! example after adding or pruning corpus files, then commit the
//! updated baseline.

use std::collections::BTreeSet;
use std::fs;
use std::path::PathBuf;

use crystal_cif_fmt::{parse_cif, DataBlock, DataBlockMember, DataItems};

fn corpus_dirs() -> Vec<PathBuf> {
    // The real-data corpus lives with the parser crate. The io
    // crate reaches it through the workspace root.
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("workspace root")
        .join("crystal_cif_fmt/tests/real_data");
    vec![root.join("iucr"), root.join("cod"), root.join("cod_sg")]
}

fn collect_tags(doc: &crystal_cif_fmt::CifDocument, out: &mut BTreeSet<String>) {
    for block in doc.data_blocks().unwrap_or(&Vec::new()) {
        collect_block_tags(block, out);
    }
}

fn collect_block_tags(block: &DataBlock, out: &mut BTreeSet<String>) {
    for member in block.members() {
        match member {
            DataBlockMember::DataItems(items) => collect_item_tags(items, out),
            DataBlockMember::SaveFrame(frame) => {
                for items in frame.data_items() {
                    collect_item_tags(items, out);
                }
            }
        }
    }
}

fn collect_item_tags(items: &DataItems, out: &mut BTreeSet<String>) {
    if let Some(data) = items.as_single_value() {
        out.insert(data.tag().as_str().to_lowercase());
    }
    if let Some(cols) = items.as_multi_values() {
        for col in cols.columns() {
            out.insert(col.tag().as_str().to_lowercase());
        }
    }
}

fn main() {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let inventory: serde_json::Value = serde_json::from_str(
        &fs::read_to_string(root.join("tests/dict_inventory.json")).expect("read dict inventory"),
    )
    .expect("dict inventory must be valid JSON");
    let items = inventory["items"].as_array().expect("items array");
    let expected: BTreeSet<String> = items
        .iter()
        .filter_map(|i| i["name"].as_str())
        .map(|n| n.to_lowercase())
        .collect();

    let mut used: BTreeSet<String> = BTreeSet::new();
    let mut files = 0u32;
    for dir in corpus_dirs() {
        for entry in fs::read_dir(&dir).expect("read corpus dir") {
            let path = entry.expect("corpus entry").path();
            if path.extension().is_none_or(|e| e != "cif") {
                continue;
            }
            let content = fs::read_to_string(&path).expect("read corpus file");
            match parse_cif(&content) {
                Ok(doc) => {
                    collect_tags(&doc, &mut used);
                    files += 1;
                }
                Err(errors) => {
                    panic!("corpus file {:?} failed to parse: {errors:?}", path);
                }
            }
        }
    }

    let distinct = used.len();
    let covered: BTreeSet<String> = used.into_iter().filter(|t| expected.contains(t)).collect();
    let baseline = serde_json::json!({
        "schema_version": 1,
        "note": "Dictionary-item coverage of the real-data corpora, \
                 generated by examples/dict_coverage_gen.rs. Failures \
                 in tests/dict_coverage.rs mean the corpus lost \
                 coverage; regenerate and review before committing.",
        "corpora": ["tests/real_data/iucr", "tests/real_data/cod", "tests/real_data/cod_sg"],
        "files": files,
        "total_items": expected.len(),
        "covered": covered.len(),
        "distinct_tags_used": distinct,
    });
    let out_path = root.join("tests/dict_coverage_baseline.json");
    fs::write(
        &out_path,
        serde_json::to_string_pretty(&baseline).unwrap() + "\n",
    )
    .unwrap();
    println!(
        "wrote {out_path:?}: {files} files, {}/{} items covered",
        covered.len(),
        expected.len()
    );
}
